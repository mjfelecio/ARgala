"""Adapt approved outlined masters without changing their paths or typography.

Run from the repo root: python3 scripts/generate-brand-geometry.py
The SVG masters are tooling inputs; Metro bundles only the generated geometry.
"""
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
SVG = '{http://www.w3.org/2000/svg}'


def read(name):
    return ET.parse(ROOT / 'assets' / 'brand' / f'{name}.svg').getroot()


primary = read('primary')
horizontal = read('horizontal')
arch = read('arch')
journey = read('journey')
data = {
    'arch': arch.find(f'{SVG}path[@id="arch"]').get('d'),
    'crossbar': arch.find(f'{SVG}path[@id="crossbar"]').get('d'),
    'letters': [dict(d=p.get('d'), transform=p.get('transform'))
                for p in primary.find(f'{SVG}g[@id="wordmark-AR-bold-gala-regular"]')],
    'lockups': {name: dict(viewBox=root.get('viewBox'),
                          arch=root[0].get('transform'),
                          wordmark=root[1].get('transform'))
                for name, root in [('primary', primary), ('horizontal', horizontal)]},
    'journey': [dict(tag=p.tag.removeprefix(SVG), **p.attrib) for p in journey],
}
(ROOT / 'src' / 'ui' / 'brand-geometry.ts').write_text(
    '// Generated by scripts/generate-brand-geometry.py from approved outlined masters.\n'
    '// Preserve exact paths, group transforms and bold AR / regular gala lettering.\n'
    'export const brandGeometry = ' + json.dumps(data, indent=2) + ' as const;\n')

# Uniformly inset the supplied adaptive artwork 10% around its canvas center.
# Its unmodified outer pixels exceed Android's central 66/108 safe circle;
# identical padding on both layers preserves proportions and themed-icon shape.
foreground = read('adaptive-foreground')[0]
for name, monochrome in [('adaptive-foreground-safe', False), ('monochrome', True)]:
    paths = ''.join(
        f'      <path d="{p.get("d")}" fill="{"#FFFFFF" if monochrome else p.get("fill")}"/>\n'
        for p in foreground)
    (ROOT / 'assets' / 'brand' / f'{name}.svg').write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
        'viewBox="0 0 1024 1024">\n'
        '  <g transform="translate(51.2 51.2) scale(.9)">\n'
        f'    <g transform="{foreground.get("transform")}">\n'
        f'{paths}'
        '    </g>\n  </g>\n</svg>\n')
